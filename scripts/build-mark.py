"""Build the website's Avior Studio mark from the locked spritesmith.sprite@1 document.

Usage:
    python art/ibis-2026/locked/tools/sprite_pipeline.py art/ibis-2026/locked/config.json /tmp/ibis
    python scripts/build-mark.py /tmp/ibis

Needs Pillow and NumPy (the pipeline also needs SciPy). The first command cuts the painting into the sprite and
its 4× part images; this script turns that output into everything the site ships:

- public/mark/atlas.webp: every 4× part packed into one image, so the mark costs one request.
- src/styles/mark.css: one absolutely placed layer per sprite layer, each showing its region of the atlas, and
  the idle rig as CSS keyframes. The site ships no JavaScript, so the animation is CSS only. Frames whose values
  lie on the straight line between their neighbours are dropped; opacity hand-overs stay instant.
- src/components/AviorMark.astro: the markup for those layers.
- Still images of the rest pose: public/mark/mark.png and mark-96.png (transparent), public/favicon.png, public/logo-mark.png and
  public/apple-touch-icon.png (charcoal rounded tiles) and public/logo.png (the share image).
"""
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = Path(sys.argv[1]).resolve()
CHARCOAL = (37, 36, 36, 255)            # #252424, the ground the mark was painted for
K = 4                                   # part images are 4× the 256 px canvas
GUTTER = 2

doc = json.loads((SRC / 'sprite.json').read_text())
rig = json.loads((SRC / 'rig.json').read_text())
CANVAS = doc['canvas'][0]
rest = doc['rest']
parts = {l['layer']: Image.open(SRC / 'parts@4x' / f"{l['asset']}.png").convert('RGBA') for l in rest}

# ---- Atlas: shelf-pack the parts, tallest first, with a transparent gutter so scaled neighbours never bleed.
AW = 1024
order = sorted(rest, key=lambda l: -parts[l['layer']].height)
place, x, y, shelf = {}, GUTTER, GUTTER, 0
for l in order:
    im = parts[l['layer']]
    if x + im.width + GUTTER > AW:
        x, y, shelf = GUTTER, y + shelf + GUTTER, 0
    place[l['layer']] = (x, y)
    x += im.width + GUTTER
    shelf = max(shelf, im.height)
AH = y + shelf + GUTTER
atlas = Image.new('RGBA', (AW, AH), (0, 0, 0, 0))
for name, (px, py) in place.items():
    atlas.paste(parts[name], (px, py))
(ROOT / 'public/mark').mkdir(parents=True, exist_ok=True)
atlas.save(ROOT / 'public/mark/atlas.webp', 'WEBP', quality=90, alpha_quality=95, method=6)

# ---- Keyframes from the rig. Every layer steps from rest by (dx, dy, da, sx, sy, o).
N = len(rig['frames'])
loop_ms = sum(f['ms'] for f in rig['frames'])
FIELDS = ('dx', 'dy', 'da', 'sx', 'sy', 'o')
DEFAULT = {'dx': 0.0, 'dy': 0.0, 'da': 0.0, 'sx': 1.0, 'sy': 1.0, 'o': 1.0}
track = {l['layer']: np.array([[DEFAULT[k] for k in FIELDS]] * N, dtype=float) for l in rest}
for f, frame in enumerate(rig['frames']):
    for step in frame['slots']:
        for i, k in enumerate(FIELDS):
            if k in step:
                track[step['slot']][f, i] = step[k]
TOL = np.array([0.02, 0.02, 0.02, 0.0004, 0.0004, 0.006])   # canvas px, degrees, scale, opacity


def pct(t):
    return f'{t * 100:.7g}%'


def value(row):
    dx, dy, da, sx, sy, o = row
    tf = []
    if abs(dx) > 1e-4 or abs(dy) > 1e-4:
        tf.append(f'translate({dx / CANVAS * 100:.4f}cqw,{dy / CANVAS * 100:.4f}cqw)')
    if abs(da) > 1e-4:
        tf.append(f'rotate({da:.3f}deg)')
    if abs(sx - 1) > 1e-5 or abs(sy - 1) > 1e-5:
        tf.append(f'scale({sx:.4f},{sy:.4f})')
    return f"transform:{' '.join(tf) or 'none'};opacity:{o:.3f}"


def keyframes(rows):
    """(time, row) stops for one loop: drop frames that linear interpolation reproduces, keep jumps instant."""
    pts = [(f / N, rows[f]) for f in range(N)] + [(1.0, rows[0])]
    out = []
    for f in range(N):
        # An opacity jump (a hand-over between layers) happens at the frame boundary, not across a frame.
        if f > 0 and abs(rows[f][5] - rows[f - 1][5]) > 0.3:
            out.append((f / N - 0.0001, rows[f - 1]))
        out.append(pts[f])
    out.append(pts[-1])
    keep = [out[0]]
    i = 0
    while i < len(out) - 1:
        j = i + 1
        while j + 1 < len(out):
            (t0, a), (t1, b) = out[i], out[j + 1]
            if t1 - t0 < 1e-9:
                break
            ok = all(np.all(np.abs(out[m][1] - (a + (b - a) * (out[m][0] - t0) / (t1 - t0))) <= TOL)
                     for m in range(i + 1, j + 1))
            if not ok:
                break
            j += 1
        keep.append(out[j])
        i = j
    return keep


css = [
    '/* Generated by scripts/build-mark.py from art/ibis-2026/locked. Do not edit by hand. */',
    '.avior-mark{position:relative;container-type:inline-size;aspect-ratio:1;width:100%}',
    '.avior-mark>i{position:absolute;display:block;background:url(/mark/atlas.webp) no-repeat;'
    f'animation:var(--n) {loop_ms}ms linear infinite;animation-play-state:var(--play,running)}}',
]
static_hidden = []
for idx, l in enumerate(rest):
    name = l['layer']
    im = parts[name]
    pw, ph = im.width, im.height
    px, py = place[name]
    left, top = l['x'] - l['w'] / 2, l['y'] - l['h'] / 2
    bx = px / (AW - pw) * 100 if AW > pw else 0
    by = py / (AH - ph) * 100 if AH > ph else 0
    rows = track[name]
    animated = np.ptp(rows, axis=0).max() > 1e-6
    is_piece = name.startswith('sweep')
    base_o = 0 if is_piece else 1                     # without motion the whole ring shows and its pieces hide
    rule = (f'.avior-mark>.m{idx}{{left:{left / CANVAS * 100:.4f}%;top:{top / CANVAS * 100:.4f}%;'
            f'width:{l["w"] / CANVAS * 100:.4f}%;height:{l["h"] / CANVAS * 100:.4f}%;'
            f'background-size:{AW / pw * 100:.4f}% {AH / ph * 100:.4f}%;background-position:{bx:.4f}% {by:.4f}%;'
            f'opacity:{base_o}' + (f';--n:am{idx}' if animated else ';animation:none') + '}')
    css.append(rule)
    if animated:
        stops = keyframes(rows)
        css.append(f'@keyframes am{idx}{{' + ''.join(f'{pct(t)}{{{value(r)}}}' for t, r in stops) + '}')
    if is_piece:
        static_hidden.append(idx)
css.append('.avior-mark.still>i{animation:none}')
css.append('@media (prefers-reduced-motion:reduce){.avior-mark>i{animation:none!important}}')
(ROOT / 'src/styles/mark.css').write_text('\n'.join(css) + '\n')

layers = ''.join(f'<i class="m{i}"></i>' for i in range(len(rest)))
(ROOT / 'src/components/AviorMark.astro').write_text(f'''---
// Generated by scripts/build-mark.py from art/ibis-2026/locked. Do not edit by hand.
import '../styles/mark.css';

interface Props {{
	still?: boolean;
	label?: string;
	class?: string;
}}

const {{ still = false, label = 'Avior Studio: a white ibis standing in still water above its reflection, inside a dry-brush ring', class: extra = '' }} = Astro.props;
---

<div class:list={{['avior-mark', {{ still }}, extra]}} role="img" aria-label={{label}}>{layers}</div>
''')

# ---- Still images of the rest pose: the bird, the water and the whole ring (not its pieces).
hi = Image.new('RGBA', (CANVAS * K, CANVAS * K), (0, 0, 0, 0))
for l in rest:
    if l['layer'].startswith('sweep'):
        continue
    im = parts[l['layer']]
    hi.alpha_composite(im, (round((l['x'] - l['w'] / 2) * K), round((l['y'] - l['h'] / 2) * K)))
hi.resize((512, 512), Image.LANCZOS).save(ROOT / 'public/mark/mark.png', optimize=True)
hi.resize((96, 96), Image.LANCZOS).save(ROOT / 'public/mark/mark-96.png', optimize=True)   # header and footer


def tile(size, radius, inset):
    """The mark on a charcoal rounded square; inset is the margin as a fraction of the side."""
    big = size * 4
    ground = Image.new('RGBA', (big, big), (0, 0, 0, 0))
    mask = Image.new('L', (big, big), 0)
    from PIL import ImageDraw
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, big - 1, big - 1), radius=round(radius * big), fill=255)
    ground.paste(Image.new('RGBA', (big, big), CHARCOAL), (0, 0), mask)
    m = round(big * (1 - 2 * inset))
    ground.alpha_composite(hi.resize((m, m), Image.LANCZOS), ((big - m) // 2, (big - m) // 2))
    return ground.resize((size, size), Image.LANCZOS)


tile(64, 0.2, 0.0).save(ROOT / 'public/favicon.png', optimize=True)
tile(256, 0.2, 0.0).save(ROOT / 'public/logo-mark.png', optimize=True)
apple = tile(180, 0.0, 0.04)
apple.save(ROOT / 'public/apple-touch-icon.png', optimize=True)
share = Image.new('RGBA', (1200, 630), CHARCOAL)
share.alpha_composite(hi.resize((560, 560), Image.LANCZOS), ((1200 - 560) // 2, 35))
share.convert('RGB').save(ROOT / 'public/logo.png', optimize=True)

print(f'atlas {AW}x{AH}, {(ROOT / "public/mark/atlas.webp").stat().st_size} bytes; '
      f'css {(ROOT / "src/styles/mark.css").stat().st_size} bytes; {len(rest)} layers, loop {loop_ms} ms')
